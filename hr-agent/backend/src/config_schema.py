# ---------------------------------------------------------------------------
# Lookups
# ---------------------------------------------------------------------------

_BY_KEY: dict[str, ConfigField] = {f.key: f for f in FIELDS}
_BY_ATTR: dict[str, ConfigField] = {f.settings_attr: f for f in FIELDS}


def get_field(key: str) -> ConfigField | None:
    return _BY_KEY.get(key)


def get_field_by_attr(attr: str) -> ConfigField | None:
    return _BY_ATTR.get(attr)


def all_keys() -> list[str]:
    return list(_BY_KEY.keys())


def secret_keys() -> set[str]:
    return {f.key for f in FIELDS if f.is_secret}


def fields_for_group(group: str) -> list[ConfigField]:
    return [f for f in FIELDS if f.group == group]


def schema_payload() -> dict[str, Any]:
    """JSON-serializable schema for the frontend form generator."""
    groups: dict[str, dict[str, Any]] = {}
    for g in GROUPS:
        groups[g] = {"name": g, "fields": []}
    for f in FIELDS:
        d = asdict(f)
        groups.setdefault(f.group, {"name": f.group, "fields": []})
        groups[f.group]["fields"].append(d)
    return {"groups": [groups[g] for g in GROUPS]}
