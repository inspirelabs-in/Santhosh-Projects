"""Registry of UI-managed configuration fields.

Drives the admin Settings UI: groups, types, validation, secret flags,
hot-reloadable flags, and which integration-test probe each field maps to.

Bootstrap-only env vars (DATABASE_URL, REDIS_URL, JWT_SIGNING_SECRET, etc.)
are deliberately NOT listed here — they cannot be edited at runtime.

Adding a new admin-editable setting = add one ConfigField entry. The frontend
form is generated automatically from `/admin/config/schema`.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Any, Literal


FieldType = Literal[
    "string",
    "secret",
    "int",
    "float",
    "bool",
    "select",
    "json",
    "url",
    "email",
    "textarea",
]


@dataclass
class ConfigField:
    key: str  # canonical env-var-style name, e.g. LLM_DAILY_BUDGET_USD
    settings_attr: str  # corresponding pydantic Settings attr (lowercase)
    group: str  # tab in the UI
    subgroup: str = ""  # collapsible subsection
    label: str = ""
    help: str = ""
    type: FieldType = "string"
    default: Any = None
    options: list[str] | None = None  # for select
    min: float | None = None
    max: float | None = None
    is_secret: bool = False
    hot_reload: bool = True  # if False, change requires worker/poller restart
    test_integration: str | None = None  # key in integration_tests probe map
    advanced: bool = False  # hide behind "Show advanced" toggle


